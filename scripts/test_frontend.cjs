const test=require('node:test');
const assert=require('node:assert/strict');
const C=require('../assets/radar-core.js');
const now=new Date('2026-10-29T09:00:00+09:00');
const base={mode:'beneficiary',opens:'2026-10-20',deadline:'2026-10-29'};
test('date-only cutoff today is not assumed 23:59',()=>assert.equal(C.deadline(base,now).code,'today_unknown'));
test('exact cutoff is honoured',()=>assert.equal(C.deadline({...base,deadline:'2026-10-29T08:59:00+09:00'},now).code,'closed'));
test('exact future cutoff and known start',()=>assert.equal(C.deadline({...base,deadline:'2026-10-29T10:00:00+09:00'},now).code,'open'));
test('date-only future means time unverified',()=>assert.equal(C.deadline({...base,deadline:'2026-11-01'},now).code,'open_date'));
test('no start date cannot imply application open',()=>assert.equal(C.deadline({...base,opens:null,deadline:'2026-11-01'},now).code,'upcoming'));
test('discovery may be closed independently of verification',()=>assert.equal(C.deadline({...base,mode:'discovery',deadline:'2026-10-28'},now).code,'closed'));
test('operator deadline independent of recruitment type',()=>assert.equal(C.deadline({...base,mode:'operator'},now).code,'today_unknown'));
test('scheduled opening',()=>assert.equal(C.deadline({...base,opens:'2026-11-01',deadline:'2026-11-03'},now).code,'scheduled'));
test('invalid date is unknown',()=>assert.equal(C.deadline({...base,deadline:'2026-02-30'},now).code,'unknown'));
test('references are not applications',()=>assert.equal(C.deadline({...base,mode:'reference'},now).code,'not_application'));
test('unknown URL host not official',()=>assert.equal(C.sourceURL('https://fake.go.kr.evil.example/a'),null));
test('all kr domains not trusted',()=>assert.equal(C.sourceURL('https://arbitrary.kr/a'),null));
test('key in URL rejected',()=>assert.equal(C.sourceURL('https://www.bizinfo.go.kr/a?crtfcKey=abc'),null));
test('approved official link',()=>assert.ok(C.sourceURL('https://www.nipa.kr/home/bsnsAll/0/nttDetail?nttNo=1')));
test('CSV formula neutralized with leading spaces',()=>assert.equal(C.csvCell(' =HYPERLINK("x")'),'"\' =HYPERLINK(""x"")"'));
test('CSV normal Korean preserved',()=>assert.equal(C.csvCell('지원공고'),'"지원공고"'));
test('XSS escaped',()=>assert.equal(C.esc('<img onerror="x">'),'&lt;img onerror=&quot;x&quot;&gt;'));
test('36h stale flag',()=>assert.equal(C.stale('2026-10-27T00:00:00+09:00',now),true));
test('recent timestamp fresh',()=>assert.equal(C.stale('2026-10-29T08:00:00+09:00',now),false));
test('multiyear retained',()=>assert.deepEqual(C.years({year:2026,years:[2026,2027]}),[2026,2027]));
